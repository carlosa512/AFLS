/**
 * Heritage name pools for everyone the engine names: players, coaches, scouts, medical staff, officials.
 * Moddable: replace freely, but keep the exports and their shapes.
 *
 * How a name is made: the generator first picks a heritage (a weighted draw whose mix depends on who is being
 * named: a position's skew for players, the staff mixes for the rest), then draws a surname from
 * `SURNAMES[heritage]` and a first name from `MEN_FIRST[heritage]` or `WOMEN_FIRST[heritage]`, each by weight.
 * A name may sit in several buckets at different weights (Washington is common among Black families and
 * rare among white ones), so one pool never has to guess the other's shares.
 *
 * Where the numbers come from. They are estimates written from memory of the published tables (the Census and
 * SSA files were out of reach), rounded, and good for ordering and rough shares, not for decimals:
 *  - Surnames in white, black, hispanic and asian: the 2010 US Census count of the name times that group's
 *    share of its bearers, in thousands of people (Smith is 1730 white and 565 black; Garcia is mostly
 *    Hispanic). Each list is only the head of the distribution, so the weights are NOT shares of the group and
 *    must not be normalised to sum to anything: the generator only compares them within a list. South Asian
 *    names are kept small on purpose (NFL rosters have almost none) and Filipino names are the Spanish-derived
 *    ones the Census splits between Asian and Hispanic.
 *  - Surnames in pacific, native, african and international: relative weights from 1 to 100. The list is
 *    the whole pool. Native names are mostly common English or Spanish-origin names found among Native
 *    families (Locklear, Oxendine, Hunt) plus the high-share ones (Begay, Yazzie, Benally).
 *  - First names: relative weights from 1 to 100 per list, the top name near 100, anchored to Social Security
 *    name popularity for the birth years. `young` is men born about 1997-2008 (players); `older` is men born
 *    about 1955-1995 (coaches, scouts, medical staff, officials); women are born about 1960-2000 (staff). SSA
 *    publishes nothing by race, so the group-characteristic names (Jaylen, DeAndre, Sione, Chukwuma) are
 *    estimates from rosters and community name research. Every bucket also carries the names all groups share
 *    (Michael, Christopher, Anthony ...) at weights that fit that group, and the short forms NFL rosters use
 *    (Mike, Chris, Matt, Josh, Nick) at sensible shares.
 *
 * Entries are real, common names only: no joke or stereotype names, and the rare surnames tied to one famous
 * person (Mahomes, Kelce, Brees ...) are left out. Characters: ASCII letters and the apostrophe
 * (O'Neal, D'Angelo), no hyphen, space, period, accent or suffix; surnames of 14 letters or fewer where
 * possible (16 at most). A name appears once per list, and each list is sorted by weight, heaviest first.
 */

