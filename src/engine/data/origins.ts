/**
 * Where players come from: US colleges by tier, the International Pathway's countries, and the Canadian league.
 * Real school names only (places and names, no nicknames, marks or colors); moddable data like the name pools.
 *
 * **Append-only:** a player stores an index into `ORIGINS` (`Player.origin`), so an entry never moves. New schools
 * go at the end. College weights are each school's rough count of NFL players on rosters, which sets how often it
 * turns up within its tier (the tier itself comes from `origin.ts`). Tiers: the four power conferences and Notre
 * Dame, the Group of 5, FCS, and Division II/III and NAIA. Sources: docs/superpowers/specs/2026-10-27-player-origins-design.md.
 */

export type OriginKind = 'college' | 'pathway' | 'cfl';
export type OriginTier = 'power' | 'group5' | 'fcs' | 'small';
export interface Origin {
  name: string;
  kind: OriginKind;
  /** Colleges only. */
  tier?: OriginTier;
  /** Colleges only: relative NFL output within the tier. */
  weight?: number;
}

const c = (name: string, tier: OriginTier, weight: number): Origin => ({ name, kind: 'college', tier, weight });
const country = (name: string): Origin => ({ name, kind: 'pathway' });

